  const MiniRoyaleLocalizations(this.locale);

  final String locale;

  static MiniRoyaleLocalizations fromLocale(String locale) =>
      MiniRoyaleLocalizations(locale);

  static MiniRoyaleLocalizations fromContext(
    BuildContext context, {
    bool listen = true,
  }) {
    final scope = listen
        ? context.dependOnInheritedWidgetOfExactType<GameUiSettingsScope>()
        : context.getInheritedWidgetOfExactType<GameUiSettingsScope>();
    final settings = scope?.settings;
    if (settings != null) return MiniRoyaleLocalizations(settings.locale);
    try {
      final locale = listen
          ? context.watch<LocaleProvider>().locale
          : context.read<LocaleProvider>().locale;
      return MiniRoyaleLocalizations(locale);
    } on ProviderNotFoundException {
      return const MiniRoyaleLocalizations('zh-Hant');
    }
  }

  String get normalizedLocale => locale.toLowerCase().replaceAll('_', '-');

  String text(String key) {
    final table = normalizedLocale == 'en' || normalizedLocale.startsWith('en-')
        ? _en
        : normalizedLocale == 'ja' || normalizedLocale.startsWith('ja-')
        ? _ja
        : _zhHant;
    return table[key] ?? _zhHant[key] ?? key;
  }

  Map<String, String> get _activeTable =>
      normalizedLocale == 'en' || normalizedLocale.startsWith('en-')
      ? _en
      : normalizedLocale == 'ja' || normalizedLocale.startsWith('ja-')
      ? _ja
      : _zhHant;

  @override
  String? operator [](Object? key) => _activeTable[key] ?? _zhHant[key];

  @override
  void operator []=(String key, String value) =>
      throw UnsupportedError('Mini Royale translations are read-only.');

  @override
  void clear() =>
      throw UnsupportedError('Mini Royale translations are read-only.');

  @override
  String? remove(Object? key) =>
      throw UnsupportedError('Mini Royale translations are read-only.');

